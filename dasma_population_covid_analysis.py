import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# Display plots inline in Jupyter notebooks
# %matplotlib inline

def process_covid_data(input_file, output_file, population_group):
    """
    Generate synthetic COVID-19 data and create visualizations.
    
    Args:
        input_file: CSV file with barangay names
        output_file: Output CSV for generated data
        population_group: Label for charts (e.g., "More than 10,000 Population")
    
    Visualizations:
        1. Scatter plot: Confirmed Cases vs Recoveries
        2. Line graph: Cases, Recoveries, Deaths by Barangay
        3. Bar chart: Cases, Recoveries, Deaths by Barangay
        4. Pie chart: Proportions of total cases/recoveries/deaths
        5. Histogram: Distribution of cases, recoveries, deaths
    """
    # Load data from CSV
    df = pd.read_csv(input_file)

    # Generate random COVID-19 data
    df['ConfirmedCases'] = np.random.randint(50, 5000, size=len(df))
    df['Recoveries'] = df['ConfirmedCases'] - np.random.randint(0, df['ConfirmedCases'] // 2, size=len(df))
    df['Deaths'] = np.random.randint(0, df['ConfirmedCases'] // 4, size=len(df))

    # Save generated data to new CSV
    df.to_csv(output_file, index=False)

    # 1. Scatter Plot: Confirmed Cases vs Recoveries
    plt.figure(figsize=(8, 6))
    plt.scatter(df['ConfirmedCases'], df['Recoveries'], color='blue')
    plt.title(f'Confirmed Cases vs Recoveries - {population_group}')
    plt.xlabel('Confirmed Cases')
    plt.ylabel('Recoveries')
    plt.grid(True)
    plt.show()

    # 2. Line Graph: Cases, Recoveries, Deaths by Barangay
    plt.figure(figsize=(10, 6))
    plt.plot(df['Barangay Name'], df['ConfirmedCases'], label='Confirmed Cases', marker='o', color='blue')
    plt.plot(df['Barangay Name'], df['Recoveries'], label='Recoveries', marker='o', color='green')
    plt.plot(df['Barangay Name'], df['Deaths'], label='Deaths', marker='o', color='red')
    plt.xticks(rotation=90)
    plt.title(f'COVID-19 Data by Barangay - {population_group}')
    plt.xlabel('Barangay')
    plt.ylabel('Count')
    plt.legend()
    plt.show()

    # 3. Bar Graph: Cases, Recoveries, Deaths by Barangay
    plt.figure(figsize=(12, 6))
    bar_width = 0.25
    bar_positions = np.arange(len(df['Barangay Name']))
    plt.bar(bar_positions, df['ConfirmedCases'], color='purple', width=bar_width, label='Confirmed Cases')
    plt.bar(bar_positions + bar_width, df['Recoveries'], color='green', width=bar_width, label='Recoveries')
    plt.bar(bar_positions + 2 * bar_width, df['Deaths'], color='red', width=bar_width, label='Deaths')
    plt.xticks(bar_positions + bar_width, df['Barangay Name'], rotation=90)
    plt.title(f'COVID-19 Data by Barangay - {population_group}')
    plt.xlabel('Barangay')
    plt.ylabel('Count')
    plt.legend()
    plt.tight_layout()
    plt.show()

    # 4. Pie Chart: Proportions of Cases, Recoveries, Deaths
    labels = ['Confirmed Cases', 'Recoveries', 'Deaths']
    sizes = [df['ConfirmedCases'].sum(), df['Recoveries'].sum(), df['Deaths'].sum()]
    colors = ['blue', 'green', 'red']
    plt.figure(figsize=(6, 6))
    plt.pie(sizes, labels=labels, colors=colors, autopct='%1.1f%%', startangle=90)
    plt.title(f'COVID-19 Proportions - {population_group}')
    plt.show()

    # 5. Histograms: Distribution of Cases, Recoveries, Deaths
    plt.figure(figsize=(6, 5))
    plt.hist(df['ConfirmedCases'], bins=10, color='blue', edgecolor='black', alpha=0.5, label='Confirmed Cases')
    plt.hist(df['Recoveries'], bins=10, color='green', edgecolor='black', alpha=0.5, label='Recoveries')
    plt.hist(df['Deaths'], bins=10, color='red', edgecolor='black', alpha=0.5, label='Deaths')
    plt.title(f'Distribution of Cases, Recoveries, Deaths - {population_group}')
    plt.xlabel('Count')
    plt.ylabel('Frequency')
    plt.legend()
    plt.grid(True)
    plt.show()

# Process and visualize data for both population groups
process_covid_data('dasma_greater_than_10000_in_2020.csv', 'covid_data_greater_than_10000.csv', 'More than 10,000 Population')
process_covid_data('dasma_less_than_10000_in_2020.csv', 'covid_data_less_than_10000.csv', 'Less than 10,000 Population')
