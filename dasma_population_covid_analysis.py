import requests
from bs4 import BeautifulSoup
import pandas as pd

# URL of the webpage barangay population data
url = 'https://www.citypopulation.de/en/philippines/dasmarinas/'

# Fetch the HTML content from the URL
response = requests.get(url)
html_content = response.text

# Parse HTML using BeautifulSoup
soup = BeautifulSoup(html_content, 'html.parser')

# Find the population data table by its class name
table = soup.find('table', {'class': 'data'})

# Extract table rows
rows = table.find_all('tr')

# Initialize list to hold barangay data
barangay_data = []

# Iterate through each row, skipping the header
for row in rows[1:]:
    columns = row.find_all('td')
    if not columns:
        continue  # Skip empty rows

    # Extract data from columns
    barangay_name = columns[0].get_text(strip=True)
    status = columns[1].get_text(strip=True)
    population_2000 = columns[2].get_text(strip=True)
    population_2010 = columns[3].get_text(strip=True)
    population_2015 = columns[4].get_text(strip=True)
    population_2020 = columns[5].get_text(strip=True)

    # Append data to the list
    barangay_data.append({
        "Barangay Name": barangay_name,
        "Status": status,
        "Population in 2000": population_2000,
        "Population in 2010": population_2010,
        "Population in 2015": population_2015,
        "Population in 2020": population_2020
    })

# Convert list of dictionaries to DataFrame
df = pd.DataFrame(barangay_data)

# Save DataFrame to CSV
df.to_csv('dasma_barangay_population.csv', index=False)

# ============================================================================
# PART 2: DATA CLEANING AND FILTERING
# ============================================================================

# Reload the data from CSV
df = pd.read_csv('dasma_barangay_population.csv')

# Clean 'Population in 2020' column and convert to numeric
df['Population in 2020'] = pd.to_numeric(df['Population in 2020'].replace({',': ''}, regex=True), errors='coerce')

# Remove rows with NaN values in 'Population in 2020'
df = df.dropna(subset=['Population in 2020'])

# Filter barangays with populations greater than 10,000
df_greater_than_10000 = df[df['Population in 2020'] > 10000]
df_greater_than_10000.to_csv('dasma_greater_than_10000_in_2020.csv', index=False)

# Filter barangays with populations 10,000 or less
df_less_than_10000 = df[df['Population in 2020'] <= 10000]
df_less_than_10000.to_csv('dasma_less_than_10000_in_2020.csv', index=False)

# Confirm data export completion
print("Data export complete.")

