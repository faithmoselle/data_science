print(f"\n🍽️ SUGGESTED MEALS")
print("-" * 40)
print(tabulate(suggested_meals, headers='keys', tablefmt='grid', showindex=False))

print(f"\n💪 SUGGESTED WORKOUTS")
print("-" * 40)
print(tabulate(suggested_workouts, headers='keys', tablefmt='grid', showindex=False))

