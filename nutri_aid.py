bmi, user_bmi_category = classify_bmi(weight, height)

# Suggest meals using greedy algorithm
print("\n" + "=" * 60)
print("ANALYZING OPTIMAL MEALS...")
print("=" * 60)

suggested_meals = []
for category in ['Breakfast', 'Lunch', 'Dinner']:
    suggested_meals.append(select_meal_greedy(category, meal_data, user_profile, weight))
suggested_meals = pd.concat(suggested_meals)

# Suggest workouts based on BMI category
suggested_workouts = suggest_workouts(user_bmi_category, workout_data)

# ============================================================================
# OUTPUT RESULTS
# ============================================================================
print(f"\n📊 YOUR BMI RESULTS")
